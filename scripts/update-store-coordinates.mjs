// Regenerates src/data/store-coordinates.ts from IKEA's public store list for each catalog country.
// Usage: node scripts/update-store-coordinates.mjs
// Only stores already in src/data/stores.ts get a coordinate; the catalog itself is not changed.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { FEEDS, fetchFeed, readCatalog, root } from "./feeds.mjs";

const catalog = readCatalog();

const lines = [];
const missing = [];
for (const countryCode of Object.keys(FEEDS)) {
  const byId = new Map((await fetchFeed(countryCode)).map((s) => [String(s.id), s]));
  for (const store of catalog.filter((s) => s.countryCode === countryCode)) {
    const feed = byId.get(store.storeId);
    const lat = Number(feed?.lat), lon = Number(feed?.lng);
    if (!feed || !Number.isFinite(lat) || !Number.isFinite(lon)) {
      missing.push(store.storeId);
      continue;
    }
    lines.push(`  "${store.storeId}": { lat: ${lat.toFixed(4)}, lon: ${lon.toFixed(4)} }, // ${feed.name}`);
  }
}

const out = `// Generated by scripts/update-store-coordinates.mjs from IKEA's public store lists
// (ikea.com/<country>/<lang>/meta-data/informera/stores-detailed.json). Do not edit by hand.
// A catalog store that is missing here is left out of distance searches, not guessed.

export interface Coordinates {
  lat: number;
  lon: number;
}

export const STORE_COORDINATES: Readonly<Record<string, Coordinates>> = {
${lines.join("\n")}
};
`;
writeFileSync(join(root, "src/data/store-coordinates.ts"), out);
console.log(`wrote ${lines.length} of ${catalog.length} catalog stores; no coordinate for: ${missing.join(", ") || "none"}`);
